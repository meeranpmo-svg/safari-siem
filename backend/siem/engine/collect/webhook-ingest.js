'use strict';
/*
 * Generic inbound webhook receiver: any system that can POST JSON (a SaaS alert, a monitoring tool, a cloud service) sends
 * events into the SIEM without a custom collector.
 *   POST /ingest/webhook/<name>        (behind nginx at /ingest/, outside /api/soc: authenticated by the webhook's own token)
 *     Header X-Sentra-Token: <token>  or  Authorization: Bearer <token>   - compared in constant time with the stored SHA-256
 *     Optional HMAC: header (default X-Hub-Signature-256) = "sha256=" + hex HMAC-SHA256 of the raw body with the webhook's
 *     signing secret; checked in constant time, refused (401) when missing or wrong.
 *     Body: one JSON object or array; mapping.events_path picks the list of events inside it (e.g. "alerts").
 *     Reply: {ok, accepted, rejected, errors[first 5]}
 *   Checked from the headers BEFORE the body is read: webhook exists and is enabled, token, Content-Length within the
 *   webhook's max_kb (route cap 1 MB), and the per-webhook rate limit (requests per minute; a wrong token also counts toward
 *   a separate failed-attempt limit, so a token cannot be guessed at speed).
 * Mapping → events: mapping.fields = { <event field>: "<dot.path in the item>" } for the SIEM's own fields (message, severity,
 *   host, src_ip, dst_ip, user, action, outcome, category, event_code, ts, url, ...), mapping.static = constant fields, and
 *   mapping.keep_payload (default false - the payload may carry personal data, PDPL) adds the whole item under "data".
 *   Each event goes through the parser (src_type json unless set) and the pipeline like every other source; collector
 *   "webhook", src_id "webhook:<name>".
 * Configuration (administrator only, audited): GET/POST {P}/collect/webhooks, PUT/DELETE {P}/collect/webhooks/:name,
 *   POST {P}/collect/webhooks/:name/rotate {what: token|hmac}. The token and the signing secret are generated by the engine,
 *   shown ONCE in the reply and stored in secrets.json (sealed at rest, secretfile.js): the token only as its SHA-256, the
 *   signing secret as is (needed to verify). They are never returned again and never written to a log.
 */
const crypto = require('node:crypto');
const { HttpError, wrap, audit, prefixOf } = require('../soc/routeutil');
const { body, param } = require('../util/check');
const { tokenOk } = require('./http-ingest');
const SF = require('../secretfile');

const NAME_RE = /^[a-z0-9][a-z0-9_-]{1,39}$/;
const PATH_RE = /^[A-Za-z0-9_$@-]{1,64}(\.[A-Za-z0-9_$@-]{1,64}){0,9}$/;
const FIELDS = ['message', 'severity', 'host', 'src_ip', 'dst_ip', 'src_port', 'dst_port', 'user', 'target_user', 'action', 'outcome', 'category', 'event_code', 'ts', 'url', 'http_status', 'process', 'hash', 'dns_query'];
const SRC_TYPES = ['json', 'cef', 'leef', 'syslog'];
const ROUTE_CAP = 1024 * 1024, MAX_EVENTS = 1000, FAIL_PER_MIN = 30;
const BAD_SEG = new Set(['__proto__', 'constructor', 'prototype']);

function get(o, p) { let x = o; for (const k of String(p).split('.')) { if (x == null || typeof x !== 'object' || BAD_SEG.has(k)) return undefined; x = Array.isArray(x) && /^\d+$/.test(k) ? x[Number(k)] : Object.prototype.hasOwnProperty.call(x, k) ? x[k] : undefined; } return x; }

/* mapping (validated in full: unknown keys refused, paths checked, no prototype keys) */
function normMapping(m) {
  if (m === undefined || m === null) return { events_path: '', fields: {}, static: {}, keep_payload: false };
  if (typeof m !== 'object' || Array.isArray(m)) throw new HttpError(400, 'mapping must be an object');
  const extra = Object.keys(m).filter((k) => !['events_path', 'fields', 'static', 'keep_payload'].includes(k)); if (extra.length) throw new HttpError(400, `mapping.${extra[0]} is not a mapping field (events_path, fields, static, keep_payload)`);
  const out = { events_path: '', fields: {}, static: {}, keep_payload: m.keep_payload === true };
  if (m.events_path) { if (typeof m.events_path !== 'string' || !PATH_RE.test(m.events_path) || m.events_path.split('.').some((k) => BAD_SEG.has(k))) throw new HttpError(400, 'mapping.events_path must be a dot path (letters, digits, _ $ @ -)'); out.events_path = m.events_path; }
  for (const [kind, val] of [['fields', m.fields], ['static', m.static]]) {
    if (val === undefined || val === null) continue;
    if (typeof val !== 'object' || Array.isArray(val)) throw new HttpError(400, `mapping.${kind} must be an object`);
    for (const [k, v] of Object.entries(val)) {
      if (!FIELDS.includes(k)) throw new HttpError(400, `mapping.${kind}.${k} is not an event field (${FIELDS.join(', ')})`);
      if (typeof v !== 'string' || /[\u0000-\u001f\u007f]/.test(v) || v.length > 200) throw new HttpError(400, `mapping.${kind}.${k} must be text (max 200)`);
      if (kind === 'fields' && (!PATH_RE.test(v) || v.split('.').some((s) => BAD_SEG.has(s)))) throw new HttpError(400, `mapping.fields.${k} must be a dot path into the payload`);
      out[kind][k] = v;
    }
  }
  return out;
}
/* one payload item → the object handed to the parser */
function mapItem(item, mapping, name) {
  const o = {};
  for (const [k, p] of Object.entries(mapping.fields || {})) { const v = get(item, p); if (v === undefined || v === null || v === '') continue; o[k] = typeof v === 'object' ? JSON.stringify(v).slice(0, 2000) : String(v).slice(0, 2000); }
  for (const [k, v] of Object.entries(mapping.static || {})) if (o[k] === undefined) o[k] = v;
  if (!o.message) o.message = 'webhook ' + name + (o.action ? ': ' + o.action : '');
  if (mapping.keep_payload) o.data = item;
  o.webhook = name;
  return o;
}
function hmacOk(raw, secret, given, prefix) {
  const exp = crypto.createHmac('sha256', String(secret)).update(raw).digest('hex');
  let g = String(given || '').trim(); if (prefix && g.toLowerCase().startsWith(prefix.toLowerCase())) g = g.slice(prefix.length);
  const h = (s) => crypto.createHash('sha256').update(String(s).toLowerCase()).digest();
  return crypto.timingSafeEqual(h(g), h(exp)) && g.length === exp.length;
}

function createWebhookIngest({ config, state, parser, pipeline, log, now, secretsPath } = {}) {
  if (!state) throw new Error('webhook ingest needs state');
  const col = state.collection('webhooks'), clock = now || Date.now, L = log || { info() {}, warn() {}, every() {} };
  const secPath = secretsPath || (config && config._paths && config._paths.secrets);
  const st = {}, win = new Map();   // name → stats · name → {m, n, fails}
  const statOf = (n) => st[n] || (st[n] = { requests: 0, accepted: 0, rejected: 0, auth_failures: 0, hmac_failures: 0, rate_limited: 0, too_large: 0, bad_requests: 0, last_seen: 0 });
  const secrets = () => (config && config.secrets && config.secrets.webhooks) || {};

  function writeSecret(name, patch) {
    if (!secPath) throw new HttpError(503, 'the secrets file path is unknown - the engine was not started with a secrets.json');
    let sec = {}; try { sec = SF.read(secPath) || {}; } catch (e) { if (e.code !== 'ENOENT') throw e; }
    sec.webhooks = sec.webhooks || {};
    if (patch === null) delete sec.webhooks[name]; else sec.webhooks[name] = Object.assign({}, sec.webhooks[name] || {}, patch);
    for (const [k, v] of Object.entries(sec.webhooks[name] || {})) if (v === null) delete sec.webhooks[name][k];
    require('../onboard/store').writeJsonAtomic(secPath, sec);   // sealed at rest (secretfile.js), no plaintext .bak
    if (config) { if (!config.secrets) Object.defineProperty(config, 'secrets', { value: {}, enumerable: false, writable: true }); config.secrets.webhooks = sec.webhooks; }
  }
  const newToken = () => crypto.randomBytes(24).toString('base64url');
  const digest = (t) => 'sha256:' + crypto.createHash('sha256').update(t).digest('hex');

  /* ---------------- receiving */
  function rate(name, kind, limit) {
    const m = Math.floor(clock() / 60000), w = win.get(name) || { m, n: 0, fails: 0 };
    if (w.m !== m) { w.m = m; w.n = 0; w.fails = 0; }
    w[kind]++; win.set(name, w); return w[kind] <= limit;
  }
  function preAuth(ctx) {
    const name = String(ctx.params.name || ''), wh = NAME_RE.test(name) ? col.get(name) : null;
    if (!wh || wh.enabled === false) { ctx.fail(404, 'unknown webhook'); return false; }
    const s = statOf(name); s.requests++;
    const auth = String(ctx.headers.authorization || ''), given = ctx.headers['x-sentra-token'] || (/^Bearer\s+/i.test(auth) ? auth.replace(/^Bearer\s+/i, '') : '');
    if (!tokenOk(given, (secrets()[name] || {}).token)) {
      s.auth_failures++;
      L.every('webhook-auth-' + name, 60000, 'warn', 'webhook: rejected token', { webhook: name, ip: ctx.ip });
      if (!rate(name, 'fails', FAIL_PER_MIN)) { s.rate_limited++; ctx.fail(429, 'too many failed attempts - try again in a minute'); return false; }
      ctx.fail(401, 'invalid or missing token'); return false;
    }
    const max = Math.min(ROUTE_CAP, (wh.max_kb || 256) * 1024), len = Number(ctx.headers['content-length'] || 0);
    if (len > max) { s.too_large++; ctx.fail(413, `payload larger than ${wh.max_kb || 256} KB`); return false; }
    if (!rate(name, 'n', wh.rate_per_min || 120)) { s.rate_limited++; L.every('webhook-rate-' + name, 60000, 'warn', 'webhook: rate limit reached', { webhook: name, per_min: wh.rate_per_min || 120 }); ctx.fail(429, 'rate limit reached (' + (wh.rate_per_min || 120) + ' per minute)'); return false; }
    return true;
  }
  function handler(ctx) {
    const name = ctx.params.name, wh = col.get(name), s = statOf(name), raw = ctx.rawBody || Buffer.alloc(0);
    if (!wh) return ctx.fail(404, 'unknown webhook');
    if (raw.length > Math.min(ROUTE_CAP, (wh.max_kb || 256) * 1024)) { s.too_large++; return ctx.fail(413, `payload larger than ${wh.max_kb || 256} KB`); }
    if (wh.hmac && wh.hmac.enabled) {
      const sec = (secrets()[name] || {}).hmac_secret, given = ctx.headers[String(wh.hmac.header || 'x-hub-signature-256').toLowerCase()];
      if (!sec || !given || !hmacOk(raw, sec, given, wh.hmac.prefix === undefined ? 'sha256=' : wh.hmac.prefix)) {
        s.hmac_failures++; L.every('webhook-hmac-' + name, 60000, 'warn', 'webhook: signature missing or wrong', { webhook: name, ip: ctx.ip });
        return ctx.fail(401, 'signature missing or wrong');
      }
    }
    let doc; try { doc = JSON.parse(raw.toString('utf8') || 'null', (k, v) => (BAD_SEG.has(k) ? undefined : v)); } catch (e) { s.bad_requests++; return ctx.fail(400, 'the body must be JSON'); }
    if (doc === null || typeof doc !== 'object') { s.bad_requests++; return ctx.fail(400, 'the body must be a JSON object or array'); }
    let items = wh.mapping && wh.mapping.events_path ? get(doc, wh.mapping.events_path) : doc;
    if (items === undefined) { s.bad_requests++; return ctx.fail(400, 'events_path "' + wh.mapping.events_path + '" not found in the body'); }
    if (!Array.isArray(items)) items = [items];
    if (items.length > MAX_EVENTS) { s.bad_requests++; return ctx.fail(413, `more than ${MAX_EVENTS} events in one request`); }
    const rts = clock(), errors = []; let accepted = 0, rejected = 0;
    items.forEach((it, i) => {
      if (!it || typeof it !== 'object' || Array.isArray(it)) { rejected++; if (errors.length < 5) errors.push(`item ${i}: expected an object`); return; }
      const o = mapItem(it, wh.mapping || {}, name);
      const ev = parser.parse(JSON.stringify(o), { collector: 'webhook', src_id: 'webhook:' + name, src_type: wh.src_type || 'json', peer_ip: ctx.ip, rts, obj: o });
      pipeline.emit(ev); accepted++;
    });
    s.accepted += accepted; s.rejected += rejected; s.last_seen = rts;
    return ctx.ok({ ok: true, accepted, rejected, errors });
  }

  /* ---------------- configuration */
  function pub(w) {
    const sec = secrets()[w.name] || {};
    return Object.assign({}, w, { path: '/ingest/webhook/' + w.name, token_set: !!sec.token, hmac_secret_set: !!sec.hmac_secret, stats: Object.assign({}, statOf(w.name)) });
  }
  function validate(b, ex) {
    const w = Object.assign({}, ex || {});
    if (b.label !== undefined) w.label = b.label;
    if (b.enabled !== undefined) w.enabled = b.enabled; if (w.enabled === undefined) w.enabled = true;
    if (b.src_type !== undefined) w.src_type = b.src_type; if (!w.src_type) w.src_type = 'json';
    if (b.rate_per_min !== undefined) w.rate_per_min = b.rate_per_min; if (!w.rate_per_min) w.rate_per_min = 120;
    if (b.max_kb !== undefined) w.max_kb = b.max_kb; if (!w.max_kb) w.max_kb = 256;
    if (b.hmac_enabled !== undefined || b.hmac_header !== undefined || b.hmac_prefix !== undefined || !w.hmac) {
      const h = Object.assign({ enabled: false, header: 'x-hub-signature-256', prefix: 'sha256=' }, w.hmac || {});
      if (b.hmac_enabled !== undefined) h.enabled = b.hmac_enabled;
      if (b.hmac_header !== undefined) h.header = b.hmac_header.toLowerCase();
      if (b.hmac_prefix !== undefined) h.prefix = b.hmac_prefix;
      w.hmac = h;
    }
    if (b.mapping !== undefined) w.mapping = normMapping(b.mapping); if (!w.mapping) w.mapping = normMapping(null);
    return w;
  }
  const api = {
    list: () => col.all().sort((a, b) => a.name.localeCompare(b.name)).map(pub),
    create(b, by) {
      if (col.get(b.name)) throw new HttpError(409, 'a webhook named ' + b.name + ' already exists');
      if (col.size() >= 100) throw new HttpError(400, 'at most 100 webhooks');
      const w = validate(b, null); w.id = w.name = b.name; w.created = clock(); w.created_by = by || ''; w.updated = w.created; w.updated_by = w.created_by;
      const token = newToken(), hmac = w.hmac.enabled ? newToken() : null;
      col.put(w);
      try { writeSecret(w.name, { token: digest(token), hmac_secret: hmac }); } catch (e) { col.remove(w.name); throw e; }   // no webhook without its token
      return { webhook: pub(w), token, hmac_secret: hmac, note: 'Copy the token' + (hmac ? ' and the signing secret' : '') + ' now: they are not shown again.' };
    },
    update(name, b, by) {
      const ex = col.get(name); if (!ex) throw new HttpError(404, 'webhook not found');
      const w = validate(b, ex); w.updated = clock(); w.updated_by = by || '';
      let hmac = null;
      if (w.hmac.enabled && !(secrets()[name] || {}).hmac_secret) { hmac = newToken(); writeSecret(name, { hmac_secret: hmac }); }
      col.put(w);
      const changed = Object.keys(b).filter((k) => JSON.stringify(b[k]) !== JSON.stringify(k.startsWith('hmac_') ? (ex.hmac || {})[k.slice(5)] : ex[k]));
      return { webhook: pub(w), hmac_secret: hmac, changed };
    },
    rotate(name, what) {
      if (!col.get(name)) throw new HttpError(404, 'webhook not found');
      const v = newToken();
      if (what === 'token') writeSecret(name, { token: digest(v) }); else writeSecret(name, { hmac_secret: v });
      return what === 'token' ? { token: v } : { hmac_secret: v };
    },
    remove(name) { if (!col.get(name)) throw new HttpError(404, 'webhook not found'); col.remove(name); writeSecret(name, null); delete st[name]; win.delete(name); return { removed: name }; },
    preAuth, handler, stats: () => JSON.parse(JSON.stringify(st)),
  };
  return api;
}

function register(api, deps) {
  if (!deps.state) throw new Error('webhook ingest needs deps.state');
  const P = prefixOf(deps);
  const W = deps.webhooks || createWebhookIngest({ config: deps.config, state: deps.state, parser: deps.parser, pipeline: deps.pipeline, log: deps.log, now: deps.now });
  deps.webhooksInstance = W;
  api.route('POST', '/ingest/webhook/:name', (ctx) => W.handler(ctx), { raw: true, maxBody: ROUTE_CAP, preAuth: (ctx) => W.preAuth(ctx), noDedup: true });
  const B = `${P}/collect/webhooks`;
  const cfgBody = (b, create) => {
    const v = body(b)
      .str('label', { max: 120 })
      .bool('enabled').oneOf('src_type', SRC_TYPES)
      .int('rate_per_min', { min: 1, max: 6000 }).int('max_kb', { min: 1, max: 1024 })
      .bool('hmac_enabled').str('hmac_header', { max: 64, re: /^[A-Za-z0-9-]{1,64}$/, msg: 'hmac_header must be an HTTP header name' }).str('hmac_prefix', { max: 20, re: /^[A-Za-z0-9=:_-]{0,20}$/, msg: 'hmac_prefix: letters, digits = : _ -' });
    if (create) v.str('name', { required: true, max: 40, re: NAME_RE, msg: 'name: 2-40 lowercase letters, digits, _ and -' });
    const out = v.done();
    if (b && b.mapping !== undefined) out.mapping = b.mapping;   // checked field by field in normMapping (unknown keys refused)
    return out;
  };
  api.route('GET', B, wrap(deps, 'admin', () => ({ items: W.list(), fields: FIELDS, src_types: SRC_TYPES, limits: { max_kb: 1024, rate_per_min: 6000, events_per_request: MAX_EVENTS } })));
  api.route('POST', B, wrap(deps, 'admin', (ctx) => {
    const b = cfgBody(ctx.body, true), r = W.create(b, ctx.user);
    audit(ctx, 'collect.webhook.create', b.name, { hmac: !!(r.webhook.hmac && r.webhook.hmac.enabled), src_type: r.webhook.src_type, rate_per_min: r.webhook.rate_per_min, max_kb: r.webhook.max_kb, fields: Object.keys(r.webhook.mapping.fields) });
    return r;
  }));
  api.route('PUT', `${B}/:name`, wrap(deps, 'admin', (ctx) => {
    const name = param(ctx.params.name, 'name'), r = W.update(name, cfgBody(ctx.body, false), ctx.user);
    audit(ctx, 'collect.webhook.update', name, { changed: r.changed, hmac_secret_created: !!r.hmac_secret }); return r;
  }));
  api.route('POST', `${B}/:name/rotate`, wrap(deps, 'admin', (ctx) => {
    const name = param(ctx.params.name, 'name'), b = body(ctx.body).oneOf('what', ['token', 'hmac'], { required: true }).done();
    const r = W.rotate(name, b.what); audit(ctx, 'collect.webhook.rotate', name, { what: b.what }); return Object.assign({ note: 'Shown once - update the sender now; the old value no longer works.' }, r);
  }));
  api.route('DELETE', `${B}/:name`, wrap(deps, 'admin', (ctx) => { const name = param(ctx.params.name, 'name'), r = W.remove(name); audit(ctx, 'collect.webhook.delete', name, {}); return r; }));
}

module.exports = { register, createWebhookIngest, normMapping, mapItem, hmacOk, FIELDS };
