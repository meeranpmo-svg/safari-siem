'use strict';
/*
 * gen-core-known.js - writes install/core-known.txt: the SHA-256 of every version of the core engine files the platform has
 * ever shipped, so update-discovery.sh can tell an UNMODIFIED earlier version (safe to replace with the current file) from a
 * file someone changed on the server (left alone).
 *
 * Why: these files are patched in place on the server (install/patches/*.patch). After later commits changed lines next to a
 * patch, a server that missed one patch sat between versions and every later patch was "skipped" for ever.
 * A version is: every content of the file in git history, plus every result of applying / removing the file's own patches
 * to those contents (chains in installer order). Hashes are over the content with CR removed (a Windows checkout copies CRLF).
 *
 *   node install/gen-core-known.js            (from repos/sentra-itam; needs git and patch)
 *   node install/gen-core-known.js --check    exit 1 when core-known.txt is out of date (used by tests/core-known.test.js)
 */
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const crypto = require('node:crypto');
const cp = require('node:child_process');

const ROOT = path.resolve(__dirname, '..');
const FILES = {
  'engine/monitoring-membership.js': ['membership-hostlogs', 'membership-admin-role'],
  'engine/http.js': ['http-roles', 'http-access-gate'],
  'engine/routes.js': ['findings-python', 'assets-python', 'audit-verify', 'assets-write', 'core-writes', 'routes-viewer-roles'],
};
const OUT = path.join(__dirname, 'core-known.txt');
const sha = (s) => crypto.createHash('sha256').update(s.replace(/\r/g, '')).digest('hex');
const git = (args) => cp.execFileSync('git', args, { cwd: ROOT, encoding: 'utf8', maxBuffer: 64 << 20 });

function versions(rel, patches) {
  const seen = new Map(), queue = [];
  const add = (c) => { c = c.replace(/\r/g, ''); const h = sha(c); if (!seen.has(h)) { seen.set(h, c); queue.push(c); } };
  add(fs.readFileSync(path.join(ROOT, rel), 'utf8'));
  for (const c of git(['log', '--format=%H', '--', rel]).split('\n').filter(Boolean)) { try { add(git(['show', c + ':./' + rel])); } catch (e) { /* the file was renamed in that commit */ } }
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'core-known-'));
  const P = patches.map((p) => ({ p, text: fs.readFileSync(path.join(__dirname, 'patches', p + '.patch'), 'utf8').replace(/\r/g, '') }));
  try {
    while (queue.length && seen.size < 400) {
      const c = queue.shift();
      for (const { text } of P) for (const rev of [false, true]) {
        fs.rmSync(path.join(tmp, 'engine'), { recursive: true, force: true }); fs.mkdirSync(path.dirname(path.join(tmp, rel)), { recursive: true });
        fs.writeFileSync(path.join(tmp, rel), c);
        const r = cp.spawnSync('patch', ['-p1', '-f', '-s', '--no-backup-if-mismatch'].concat(rev ? ['-R'] : []), { cwd: tmp, input: text, encoding: 'utf8' });
        if (r.status === 0) add(fs.readFileSync(path.join(tmp, rel), 'utf8'));
      }
    }
  } finally { fs.rmSync(tmp, { recursive: true, force: true }); }
  return [...seen.keys()];
}

function build() {
  const lines = ['# core-known.txt - SHA-256 (CR removed) of every shipped version of the patched core files; generated by gen-core-known.js'];
  for (const [rel, patches] of Object.entries(FILES)) for (const h of versions(rel, patches).sort()) lines.push(h + '  ' + rel);
  return lines.join('\n') + '\n';
}

if (require.main === module) {
  const txt = build();
  if (process.argv.includes('--check')) { const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : ''; if (cur !== txt) { console.error('core-known.txt is out of date: run node install/gen-core-known.js'); process.exit(1); } console.log('core-known.txt is current'); }
  else { fs.writeFileSync(OUT, txt); console.log('wrote ' + OUT + ' (' + (txt.split('\n').length - 2) + ' versions)'); }
}
module.exports = { build, sha, FILES };
