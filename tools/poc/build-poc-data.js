/*
 * build-poc-data.js - builds ui/vendor/zyb-poc-rec.js, the recorded illustrative data of POC mode (vendor/zyb-poc.js), from the
 * platform's own browser tests: each test runs with tools/poc/playwright-recorder.js in place of Playwright, and every JSON answer
 * its pages receive from /api/... is kept. The tests use SYNTHETIC data only. Per API path the richest answer is kept (the largest
 * that is not an error); test artefacts are cleaned (markup / script text becomes "POC example", "synthetic" / "syn" become "POC").
 *   node tools/poc/build-poc-data.js --run [test ...]   run the browser tests (all, or the named ones) with the recorder, then build
 *   node tools/poc/build-poc-data.js                     build from the recordings already in tools/poc/rec/
 * The recordings and the result never hold real data: they come from tests that run against synthetic fixtures.
 */
const fs = require('fs'), path = require('path'), { spawn } = require('child_process');
const ROOT = path.resolve(__dirname, '../..'), REC = path.join(__dirname, 'rec'), UIT = path.join(ROOT, 'tests/ui'), OUT = path.join(ROOT, 'ui/vendor/zyb-poc-rec.js');
const args = process.argv.slice(2), run = args.includes('--run'), only = args.filter((a) => !a.startsWith('--'));
const PAR = Number(process.env.POC_PAR || 4), TMO = Number(process.env.POC_TIMEOUT || 240) * 1000;

function runTests() {
  fs.mkdirSync(REC, { recursive: true });
  const list = (only.length ? only : fs.readdirSync(UIT).filter((f) => f.endsWith('.test.js') && /process\.env\.PLAYWRIGHT/.test(fs.readFileSync(path.join(UIT, f), 'utf8')))).map((f) => (f.endsWith('.js') ? f : f + '.test.js'));
  let i = 0, done = 0; const t0 = Date.now();
  return new Promise((resolve) => {
    const next = () => {
      if (i >= list.length) { if (done === list.length) resolve(); return; }
      const f = list[i++], p = spawn(process.execPath, [path.join(UIT, f)], { cwd: UIT, env: Object.assign({}, process.env, { PLAYWRIGHT: path.join(__dirname, 'playwright-recorder.js'), POC_RECORD_DIR: REC }), stdio: 'ignore' });
      const k = setTimeout(() => p.kill('SIGKILL'), TMO);
      p.on('exit', () => { clearTimeout(k); done++; if (done % 20 === 0 || done === list.length) console.log(done + '/' + list.length + ' tests recorded (' + Math.round((Date.now() - t0) / 1000) + ' s)'); if (done === list.length) resolve(); else next(); });
    };
    for (let k = 0; k < Math.min(PAR, list.length); k++) next();
  });
}

const MARKUP = /<[a-z!/][^>]*>|javascript:|onerror\s*=|onload\s*=|\{\{|\$\{/i;
function clean(v) {
  if (typeof v === 'string') { if (MARKUP.test(v)) return 'POC example'; return v.replace(/\(synthetic\)/gi, '(POC)').replace(/synthetic/gi, 'POC').replace(/\bSYN\b/g, 'POC').replace(/\.syn\b/g, '.poc').replace(/-syn\b/gi, '-poc').replace(/Hunter2Secret!?/g, '[removed]'); }
  if (Array.isArray(v)) return v.map(clean);
  if (v && typeof v === 'object') { const o = {}; for (const [k, x] of Object.entries(v)) o[clean(k)] = clean(x); return o; }
  return v;
}
const empty = (b) => { if (!b || typeof b !== 'object') return true; if (b.error) return true; const s = JSON.stringify(b); return s.length < 40; };

function build() {
  const best = {}, pages = {};
  for (const f of fs.existsSync(REC) ? fs.readdirSync(REC).filter((x) => x.endsWith('.jsonl')) : []) {
    for (const line of fs.readFileSync(path.join(REC, f), 'utf8').split('\n')) {
      if (!line) continue; let r; try { r = JSON.parse(line); } catch (e) { continue; /* a line cut by a killed test */ }
      if (empty(r.body)) continue;
      if (!best[r.path] || r.size > best[r.path].size) best[r.path] = r;
      if (r.page) (pages[r.page] = pages[r.page] || new Set()).add(r.path);
    }
  }
  const map = {}; let bytes = 0;
  for (const p of Object.keys(best).sort()) { map[p] = clean(best[p].body); bytes += best[p].size; }
  const head = '// Copyright (c) 2026 Zyberon Information Technology. All rights reserved. Proprietary and confidential - see LICENSE.\n'
    + '/* zyb-poc-rec.js - GENERATED by tools/poc/build-poc-data.js from the browser tests\' SYNTHETIC data - do not edit by hand. Loaded only in POC mode\n'
    + ' * (vendor/zyb-poc.js): the answer per API path, recorded at ' + new Date().toISOString() + '; dates are moved forward to today when shown. */\n';
  // platform calls every page makes (licence, who am I, report branding): left to the live server, never counted as POC data
  const seen = {}; for (const v of Object.values(pages)) for (const x of v) seen[x] = (seen[x] || 0) + 1;
  const np = Object.keys(pages).length, COMMON = /\/(licence|roles\/me|auth\/whoami|report-brand|whoami)$/;
  const common = Object.keys(seen).filter((x) => COMMON.test(x) || (np >= 10 && seen[x] / np >= 0.3)).sort();
  for (const c of common) delete map[c];
  const pg = {}; for (const [k, v] of Object.entries(pages)) { const L0 = [...v].filter((x) => !common.includes(x)).sort(); if (L0.length) pg[k] = L0; }
  fs.writeFileSync(OUT, head + 'window.ZYB_POC_REC = ' + JSON.stringify({ recorded_at: new Date().toISOString(), common, pages: pg, map }) + ';\n');
  console.log('wrote ui/vendor/zyb-poc-rec.js: ' + Object.keys(map).length + ' API paths, ' + Math.round(bytes / 1024) + ' KB recorded, from ' + Object.keys(pages).length + ' pages');
  return { paths: Object.keys(map), pages };
}

(async () => { if (run) await runTests(); build(); })().catch((e) => { console.error(e); process.exit(1); });
module.exports = { clean };
